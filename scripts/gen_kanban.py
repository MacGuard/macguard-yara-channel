#!/usr/bin/env python3
"""Renders docs/intelligence/KANBAN.md from docs/intelligence/kanban.json (the source). No dates, no percentages. --check compares with the committed file and verifies that
every card's evidence files exist. usage: gen_kanban.py [--check]"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / 'docs' / 'intelligence' / 'kanban.json'
OUT = ROOT / 'docs' / 'intelligence' / 'KANBAN.md'


def render():
    d = json.loads(SRC.read_text(encoding='utf-8'))
    lines = ['# Kanban de MacGuard Security Intelligence / MacGuard Security Intelligence kanban', '', '*' + d['note'] + '*', '',
             'Generated by `scripts/gen_kanban.py` from `kanban.json`: edit the JSON, not this file.', '']
    for col in d['columns']:
        cards = [c for c in d['cards'] if c['column'] == col['id']]
        lines += [f"## {col['es']} / {col['en']} ({len(cards)})", '', '| ES | EN | PR | Evidence | Note |', '|---|---|---|---|---|']
        for c in cards:
            lines.append(f"| {c['es']} | {c['en']} | {c['pr'] or ''} | {', '.join('`' + e + '`' for e in c['evidence'])} | {c['note'] or ''} |")
        lines.append('')
    return '\n'.join(lines)


def missing():
    d = json.loads(SRC.read_text(encoding='utf-8'))
    return [(c['en'], e) for c in d['cards'] for e in c['evidence'] if not (ROOT / e).exists()]


def main(argv):
    out = render()
    if '--check' in argv:
        bad = missing()
        for b in bad: print('MISSING EVIDENCE', b)
        same = OUT.exists() and OUT.read_text(encoding='utf-8') == out
        print('gen_kanban:', 'matches' if same and not bad else 'differs or evidence missing')
        return 0 if same and not bad else 1
    OUT.write_text(out, encoding='utf-8'); print('wrote', OUT.relative_to(ROOT)); return 0

if __name__ == '__main__': sys.exit(main(sys.argv[1:]))
