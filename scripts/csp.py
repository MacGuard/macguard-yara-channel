#!/usr/bin/env python3
"""Content Security Policy and security headers for the public site.

GitHub Pages cannot send custom response headers, so every HTML page carries the policy in a <meta http-equiv> tag (this module injects it);
Cloudflare Pages also gets real headers from a `_headers` file generated here, which additionally cover what a meta tag cannot (frame-ancestors).
Scripts are restricted to the site itself with no inline code and no eval; styles allow inline because Mermaid writes <style> into its SVG.
All fetches of the pages are same-origin (rules, logs, release package), which `tests/test_csp.py` checks against the real pages.

usage: csp.py inject SITE_DIR            add/refresh the meta tag in every page
       csp.py headers OUT_FILE           write the Cloudflare `_headers` file"""
import os, pathlib, re, sys

# The vulnerability lookup API (gateway, macguard.intel-search/1) is OPTIONAL: only when the build sets MG_VULN_API to a plain https base does the
# policy allow that ONE extra origin for fetch (and build_site writes <meta name="mg-vuln-api"> into the hub pages). Unset: policy unchanged.
API_BASE_RE = re.compile(r'^https://([a-z0-9.-]+)(:\d{1,5})?(/[A-Za-z0-9._~/-]*)?$')


def api_base() -> str:
    v = (os.environ.get('MG_VULN_API') or '').strip()
    if not v: return ''
    if not API_BASE_RE.match(v): raise SystemExit(f'MG_VULN_API must be a plain https base URL, got {v!r}')
    return v.rstrip('/')


def api_origin() -> str:
    b = api_base()
    if not b: return ''
    m = API_BASE_RE.match(b)
    return 'https://' + m.group(1) + (m.group(2) or '')


_API = api_origin()
DIRECTIVES = ("default-src 'none'", "script-src 'self'", "style-src 'self' 'unsafe-inline'", "img-src 'self' data:", "font-src 'self'", "connect-src 'self'" + (' ' + _API if _API else ''),
              "base-uri 'none'", "form-action 'none'", "object-src 'none'")
POLICY = '; '.join(DIRECTIVES)
HEADER_POLICY = POLICY + "; frame-ancestors 'none'"   # frame-ancestors is ignored in a meta tag, so only the real header carries it
BLOCK = re.compile(r'<!--csp-->.*?<!--/csp-->', re.S)
TAG = f'<!--csp--><meta http-equiv="Content-Security-Policy" content="{POLICY}"><!--/csp-->'

def inject(site: pathlib.Path) -> int:
    n = 0
    for p in sorted(site.rglob('*.html')):
        s = BLOCK.sub('', p.read_text(encoding='utf-8'))
        m = re.search(r'<meta charset="[^"]*">', s, re.I)
        if not m: raise SystemExit(f'{p}: no <meta charset> to anchor the policy after')
        first_script = s.lower().find('<script')
        if 0 <= first_script < m.end(): raise SystemExit(f'{p}: a script comes before the policy')
        p.write_text(s[:m.end()] + TAG + s[m.end():], encoding='utf-8'); n += 1
    return n

def headers() -> str:
    return ('# Generated by scripts/csp.py; Cloudflare Pages only (GitHub Pages cannot send headers).\n/*\n'
            f'  Content-Security-Policy: {HEADER_POLICY}\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: no-referrer\n'
            '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()\n  Cross-Origin-Opener-Policy: same-origin\n'
            '  Strict-Transport-Security: max-age=31536000\n'
            '/latest.json\n  Cache-Control: public, max-age=300, must-revalidate\n/logs/*\n  Cache-Control: public, max-age=300, must-revalidate\n')

if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == 'inject': print(f'policy written to {inject(pathlib.Path(sys.argv[2]))} pages')
    elif len(sys.argv) == 3 and sys.argv[1] == 'headers': pathlib.Path(sys.argv[2]).write_text(headers()); print(f'wrote {sys.argv[2]}')
    else: sys.exit(__doc__)
